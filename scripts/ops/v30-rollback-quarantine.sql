-- RunningAI — Phase 8B rollback pre-step: make garmin_sync_attempt readable by a pre-8B jar
-- WITHOUT destroying the row.
--
-- WHEN TO RUN THIS
--   Only when rolling PRODUCTION BACK from the Phase 8B jar to a pre-8B jar (V28 or earlier)
--   AND the pre-check below reports at least one row. It is NOT a routine deployment step and
--   NOT a rollback step on its own: roll-forward (re-deploying the 8B jar) fixes the same
--   condition with nothing removed at all, and is the preferred recovery.
--
-- WHY IT IS NEEDED
--   V30 added two outcomes, STARTED and INTERRUPTED. A pre-8B jar's GarminSyncAttemptOutcome
--   enum has neither, so reading such a row throws IllegalArgumentException and the old jar
--   answers HTTP 500 on BOTH:
--       GET /api/v1/garmin/sync/status      (also what scripts/windows/status-running-ai.ps1 reads)
--       GET /api/v1/data-freshness
--   The application still STARTS cleanly, so "the old jar came up" is not evidence of a working
--   rollback. These two endpoints must be checked.
--
-- WHY NOT A PLAIN DELETE
--   garmin_sync_attempt holds exactly ONE row per athlete (uk_garmin_sync_attempt_athlete), so a
--   DELETE does not remove a log line - it removes that athlete's entire attempt record, including
--   consecutive_failure_count, consecutive_partial_count, last_failure_at and last_failure_code,
--   which are deliberately designed to SURVIVE a later success. This script copies the whole row
--   to a quarantine table first, so the rollback costs nothing that cannot be put back by
--   v30-rollback-restore.sql.
--
-- WHAT IT STILL COSTS (state this when approving)
--   While the old jar runs, the live row is absent, so a sync performed during the rollback
--   window starts a FRESH failure streak from 0. The historical streak is preserved in quarantine
--   but is not what the (8B-only) circuit breaker would read on roll-forward if a newer row has
--   since been written. No checkpoint moves: garmin_sync_state is never touched here.
--
-- PRE-CHECK (run first; if this returns 0, do NOT run this script - nothing is wrong)
--   SELECT count(*) FROM garmin_sync_attempt WHERE outcome IN ('STARTED','INTERRUPTED');

\set ON_ERROR_STOP on

BEGIN;

CREATE TABLE IF NOT EXISTS garmin_sync_attempt_v30_quarantine (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quarantined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reason         TEXT        NOT NULL,
    -- The whole row as JSONB, so this table needs no maintenance when the source table changes.
    row_data       JSONB       NOT NULL
);

INSERT INTO garmin_sync_attempt_v30_quarantine (reason, row_data)
SELECT 'V30->pre-8B rollback: outcome not in the old jar''s enum', to_jsonb(a)
FROM garmin_sync_attempt a
WHERE a.outcome IN ('STARTED', 'INTERRUPTED');

DELETE FROM garmin_sync_attempt
WHERE outcome IN ('STARTED', 'INTERRUPTED');

COMMIT;

-- POST-CHECK: live table no longer holds an unreadable outcome, and every removed row is held.
SELECT (SELECT count(*) FROM garmin_sync_attempt
        WHERE outcome IN ('STARTED','INTERRUPTED'))        AS must_be_zero,
       (SELECT count(*) FROM garmin_sync_attempt_v30_quarantine) AS rows_preserved;
