package com.runningai.draftpublish

import com.fasterxml.jackson.annotation.JsonInclude
import com.runningai.athlete.AthleteService
import com.runningai.coach.WorkoutDraftApprovalService
import org.springframework.stereotype.Service
import org.springframework.transaction.annotation.Transactional
import org.springframework.web.bind.annotation.GetMapping
import org.springframework.web.bind.annotation.RequestParam
import org.springframework.web.bind.annotation.RestController
import java.time.Clock
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId

/** What the athlete's approved plan for a day amounts to, in the three states a display can show. */
enum class TodayWorkoutStatus {
    /** An approved non-REST workout exists for the date. */
    HAS_PLAN,

    /** An approved REST day. A decision, not an absence - and it outranks "no events found". */
    REST,

    /** No draft has been approved for the date. Not the same as REST. */
    NO_PLAN,
}

/**
 * Where the answer came from. Present so a consumer can tell "RunningAI decided this" from
 * "RunningAI has decided nothing", instead of inferring it from an empty field.
 */
enum class TodayWorkoutSource { APPROVED_DRAFT, NONE }

/**
 * `GET /api/v1/today-workout`. Deliberately small and free of coaching language: it reports the
 * approved plan for one date and nothing else.
 *
 * It carries no free text on purpose. The watch-face relay is the intended consumer, and whatever
 * it is given crosses a trust boundary on the way to a device with a 14-glyph display and a pixel
 * font covering only digits, A-Z and a few symbols. Handing it a structured type and a duration
 * lets it build its own label from values it already understands; handing it a coach-written title
 * would make a display string out of free text generated by a model. [title] is therefore absent
 * from this contract rather than merely unused.
 *
 * [stale] exists for the same reason: a cached or mis-dated answer must be detectable as such by
 * the consumer rather than silently shown as today's plan.
 */
@JsonInclude(JsonInclude.Include.ALWAYS)
data class TodayWorkoutResponse(
    val date: LocalDate,
    val status: TodayWorkoutStatus,
    val source: TodayWorkoutSource,
    /** EASY / RECOVERY / LONG / THRESHOLD / INTERVAL / TEMPO / CROSS_TRAINING; null for REST and NO_PLAN. */
    val workoutType: String?,
    val totalDurationMinutes: Int?,
    /** Repetitions of the workout's repeated block, when it has one; null otherwise. */
    val repetitions: Int?,
    val approvedAt: Instant?,
    /** True when this approved draft reached Intervals.icu (or was recorded as a skipped rest day). */
    val published: Boolean,
    val publishedAt: Instant?,
    /** True when [date] is not the athlete's current date - the caller asked about another day. */
    val stale: Boolean,
    /** The athlete's current date at the time of this answer, so a consumer can check [stale] itself. */
    val athleteToday: LocalDate,
)

/**
 * Reads the approved plan for one date (Phase 8B, Workstream D).
 *
 * This exists because the watch face had no route to RunningAI at all: the relay asked
 * Intervals.icu directly for calendar events and took its REST decision from the legacy
 * `C:\running-ai\state\today_plan.json`, so an approved AI draft reached the watch only if it had
 * already been published - and a REST day decided by the coach never reached it. The approval is
 * the athlete's decision, and this is the one place that states it.
 *
 * Strictly database-only: no Garmin call, no Intervals call, no coach call, nothing published and
 * nothing written. It cannot cause a workout to exist, and it has no opinion about one - it reports
 * what was approved.
 *
 * It lives in this package rather than in `coach` because it joins the approval with its
 * publication, and `CoachArchitectureTest` forbids coach and draft sources from importing
 * `draftpublish` at all - a blunt guard, deliberately, so that the path which designs workouts can
 * never acquire a route to the one that sends them. The dependency only runs this way round.
 */
@Service
class TodayWorkoutService(
    private val approvals: WorkoutDraftApprovalService,
    private val publications: WorkoutDraftPublicationStore,
    private val athletes: AthleteService,
    private val clock: Clock,
) {

    @Transactional(readOnly = true)
    fun forDate(requested: LocalDate?): TodayWorkoutResponse {
        val today = LocalDate.now(clock.withZone(ZoneId.of(athletes.getDefaultAthlete().timezone)))
        val date = requested ?: today
        val approved = approvals.findApprovedForDate(date)
            ?: return TodayWorkoutResponse(
                date = date,
                status = TodayWorkoutStatus.NO_PLAN,
                source = TodayWorkoutSource.NONE,
                workoutType = null,
                totalDurationMinutes = null,
                repetitions = null,
                approvedAt = null,
                published = false,
                publishedAt = null,
                stale = date != today,
                athleteToday = today,
            )

        val draft = approved.draft
        val publication = publications.find(approved.approval.draftId)
        return TodayWorkoutResponse(
            date = date,
            status = if (draft.isRest) TodayWorkoutStatus.REST else TodayWorkoutStatus.HAS_PLAN,
            source = TodayWorkoutSource.APPROVED_DRAFT,
            workoutType = draft.workoutType.takeUnless { draft.isRest },
            totalDurationMinutes = draft.totalDurationMinutes.takeUnless { draft.isRest },
            // The largest repeat count in the workout: a display showing "6 x ..." is describing the
            // main set, and a warm-up is never the repeated block.
            repetitions = draft.segments.mapNotNull { it.repetitions }.filter { it > 1 }.maxOrNull(),
            approvedAt = approved.approval.approvedAt,
            published = publication != null,
            publishedAt = publication?.publishedAt,
            stale = date != today,
            athleteToday = today,
        ).also {
            check(publication?.outcome != DraftPublicationOutcome.PUBLISHED || it.publishedAt != null) {
                "a PUBLISHED publication must carry its timestamp"
            }
        }
    }
}

@RestController
class TodayWorkoutController(private val service: TodayWorkoutService) {

    /**
     * The approved plan for [date], defaulting to the athlete's today. Read-only and database-only;
     * no authentication, the same convention as the other RunningAI operational APIs (private
     * network only - the watch-face relay, not the watch, is what calls this).
     */
    @GetMapping("/api/v1/today-workout")
    fun todayWorkout(
        @RequestParam(required = false) date: LocalDate?,
    ): TodayWorkoutResponse = service.forDate(date)
}
