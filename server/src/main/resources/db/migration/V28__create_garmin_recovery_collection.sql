-- Phase 8A: what the last Garmin recovery collection attempt found for one athlete-local day.
--
-- garmin_recovery_daily stores recovery VALUES, and RecoverySnapshotService deliberately creates no
-- row for a day that produced no value at all (an empty row would read as "Garmin had data for this
-- day"). That rule is correct and unchanged - but it makes the ABSENCE of a row ambiguous in exactly
-- the way an operator planning a backfill needs resolved:
--
--     never fetched                         -> worth fetching
--     fetched, Garmin genuinely had nothing -> fetching again will not help (no watch worn that night)
--     fetch failed (429 / 401 / connector)  -> worth fetching again
--
-- One row per (athlete, recovery_date), replaced by each new attempt: this is the latest known
-- outcome for that day, not an attempt history.
--
--   outcome  STORED   the call succeeded and at least one metric carried a value
--            NO_DATA  the call succeeded and Garmin returned no usable value for any metric
--            FAILED   the call itself failed; the per-metric outcomes are NULL (nothing was returned)
--
-- The per-metric *_outcome columns mirror GarminRecoveryMapper's own per-metric verdict:
--   AVAILABLE (at least one valid value), NO_DATA / ERROR (Garmin's own status for that metric), or
--   MALFORMED (an OK metric with no usable value, an unknown status, or no entry at all).
-- Note the naming: garmin_recovery_daily.hrv_status holds GARMIN's label (e.g. BALANCED); the
-- columns here are COLLECTION outcomes and are named *_outcome so the two can never be confused.
--
-- Pure observability: nothing derives a recovery value or a baseline from this table, and a missing
-- row here never means a stored value is invalid. Rows exist only from Phase 8A onwards, so a day
-- collected before this migration has no row and is correctly reported as "not tracked".
CREATE TABLE garmin_recovery_collection (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id                BIGINT                   NOT NULL,
    recovery_date             DATE                     NOT NULL,
    outcome                   VARCHAR(16)              NOT NULL,
    attempted_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    failure_code              VARCHAR(64),
    hrv_outcome               VARCHAR(16),
    sleep_outcome             VARCHAR(16),
    resting_heart_rate_outcome VARCHAR(16),
    body_battery_outcome      VARCHAR(16),
    stress_outcome            VARCHAR(16),
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_garmin_recovery_collection_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT uk_garmin_recovery_collection_athlete_date UNIQUE (athlete_id, recovery_date),
    CONSTRAINT ck_garmin_recovery_collection_outcome CHECK (outcome IN ('STORED', 'NO_DATA', 'FAILED'))
);
