-- Phase 8A: the outcome of the LAST Garmin incremental activity sync attempt, one row per athlete.
--
-- Why this is not a column on garmin_sync_state: that table records only what SUCCEEDED
-- (high_water_started_at, last_successful_sync_at), and deliberately so - a failed run must never be
-- able to move the checkpoint. The consequence was that a failure left no trace in the database at
-- all, so an operator reading the DB could not tell
--
--     "the sync ran and Garmin genuinely had no new activity"   (no data)
-- from
--     "the sync never ran since the last success"               (not attempted)
-- from
--     "the sync ran and Garmin answered 429 / 401"              (collection failure).
--
-- This table answers exactly that question and nothing else. It is pure observability: no code reads
-- it to decide what to fetch, and writing it can never influence the checkpoint. It is a separate
-- table rather than nullable columns on garmin_sync_state precisely so that a sync which fails
-- BEFORE any success has ever happened still records its failure - garmin_sync_state cannot hold
-- such a row (both of its timestamps are NOT NULL by design).
--
--   outcome  SUCCESS  the run completed and every fetched item was ingested (failed = 0)
--            PARTIAL  the run completed but at least one item could not be mapped (failed > 0);
--                     the checkpoint is NOT advanced in this case - see GarminIncrementalSyncService
--            FAILED   the run threw: connector/Garmin failure, or the overlap window was incomplete
--
-- The counts are those of the last attempt, whatever its outcome. last_failure_at / last_failure_code
-- survive a later success on purpose ("when did this last break?"); consecutive_failure_count is
-- reset to 0 by any non-FAILED attempt, so a stuck scheduler is visible as a growing number.
CREATE TABLE garmin_sync_attempt (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id                BIGINT                   NOT NULL,
    attempted_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    outcome                   VARCHAR(16)              NOT NULL,
    failure_code              VARCHAR(64),
    fetched                   INTEGER                  NOT NULL DEFAULT 0,
    created                   INTEGER                  NOT NULL DEFAULT 0,
    updated                   INTEGER                  NOT NULL DEFAULT 0,
    skipped                   INTEGER                  NOT NULL DEFAULT 0,
    failed                    INTEGER                  NOT NULL DEFAULT 0,
    pages_fetched             INTEGER                  NOT NULL DEFAULT 0,
    checkpoint_advanced       BOOLEAN                  NOT NULL DEFAULT FALSE,
    consecutive_failure_count INTEGER                  NOT NULL DEFAULT 0,
    last_failure_at           TIMESTAMP WITH TIME ZONE,
    last_failure_code         VARCHAR(64),
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_garmin_sync_attempt_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT uk_garmin_sync_attempt_athlete UNIQUE (athlete_id),
    CONSTRAINT ck_garmin_sync_attempt_outcome CHECK (outcome IN ('SUCCESS', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_garmin_sync_attempt_counts CHECK (
        fetched >= 0 AND created >= 0 AND updated >= 0 AND skipped >= 0 AND failed >= 0
        AND pages_fetched >= 0 AND consecutive_failure_count >= 0)
);
