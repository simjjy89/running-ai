-- Phase 8B (Workstream C): every attempt to publish an APPROVED draft, including the ones that failed.
--
-- workout_draft_publication (V10) is one row per draft and stores SUCCESS ONLY, deliberately: a failed
-- publish must leave the draft publishable again, so recording the failure there would have meant either
-- a row that blocks the retry or an outcome column that lies. That decision is unchanged and this table
-- does not touch it.
--
-- What it fixes is the consequence nobody needed until publishing became real: a failure existed only in
-- the HTTP response of the request that failed. Once that response was gone, so was the fact. "Did this
-- draft ever fail to publish, how often, and against what?" was unanswerable from the database, which is
-- exactly the question asked after an external write goes wrong.
--
-- Append-only, one row per attempt (unlike V10's one row per draft), so a retry history reads in order.
--
--   outcome  PUBLISHED          written to Intervals.icu and verified
--            SKIPPED_REST_DAY   an approved rest day: nothing was sent, by design
--            ALREADY_PUBLISHED  the stored result of an earlier publish was returned; zero external calls
--            REFUSED            RunningAI itself stopped it (injury gate, unpublishable draft). Never sent
--            FAILED             the external publish threw
--
-- Two booleans carry the question that actually matters after a failure, and they are separate because
-- they are different questions:
--
--   external_write_attempted  did this attempt get as far as possibly changing Intervals.icu?
--   remote_state_certain      do we know what Intervals.icu holds now?
--
-- remote_state_certain = FALSE is the dangerous case - a timeout or dropped connection where the write
-- may or may not have landed. It is recorded rather than guessed at. The publisher already handles it
-- correctly (IntervalsWorkoutPublisher.createWithoutBlindRetry: never repeat the POST, re-list the date
-- by marker and adopt whatever the server really holds), so this column exists to make that state
-- visible afterwards, not to drive a retry. Nothing in this repository retries an external publish.
--
-- Safety of the stored content: codes and numbers only. failure_code is derived from the exception TYPE
-- and reason, never its message; http_status is Intervals.icu's own status. No response body, no workout
-- text, no API key and no prompt text can reach this table.
CREATE TABLE workout_draft_publish_attempt (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id                 BIGINT                   NOT NULL,
    approval_id              BIGINT,
    attempted_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms              BIGINT                   NOT NULL,
    outcome                  VARCHAR(32)              NOT NULL,
    failure_code             VARCHAR(64),
    http_status              INTEGER,
    intervals_operation      VARCHAR(32),
    remote_event_id          VARCHAR(128),
    external_write_attempted BOOLEAN                  NOT NULL,
    remote_state_certain     BOOLEAN                  NOT NULL,
    CONSTRAINT fk_workout_draft_publish_attempt_draft FOREIGN KEY (draft_id) REFERENCES workout_draft (id),
    CONSTRAINT fk_workout_draft_publish_attempt_approval FOREIGN KEY (approval_id)
        REFERENCES workout_draft_approval (id),
    CONSTRAINT ck_workout_draft_publish_attempt_outcome CHECK (
        outcome IN ('PUBLISHED', 'SKIPPED_REST_DAY', 'ALREADY_PUBLISHED', 'REFUSED', 'FAILED')),
    -- A successful outcome can have no failure code, and a failed/refused one must have one: the point
    -- of the table is lost the moment a failure is stored without saying what failed.
    CONSTRAINT ck_workout_draft_publish_attempt_failure CHECK (
        (outcome IN ('FAILED', 'REFUSED') AND failure_code IS NOT NULL)
        OR (outcome NOT IN ('FAILED', 'REFUSED') AND failure_code IS NULL)),
    CONSTRAINT ck_workout_draft_publish_attempt_duration CHECK (duration_ms >= 0)
);

-- The history of one draft, newest first, is the only read this table is built for.
CREATE INDEX idx_workout_draft_publish_attempt_draft ON workout_draft_publish_attempt (draft_id, attempted_at DESC);
