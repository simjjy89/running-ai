-- Phase 7B-4: append-only ledger of every lactate-threshold profile event. A row is INSERTed and
-- never UPDATEd/DELETEd, for two kinds of events:
--   applied = TRUE  : the profile actually changed (the row carries the new values and the values
--                     they replaced);
--   applied = FALSE : an observation that did NOT change the profile - e.g. a Garmin sync that
--                     reported the same values again (freshness evidence: "Garmin re-confirmed this
--                     value on date X"), or a manual PUT that re-submitted identical values.
--
-- source records WHERE the event came from: 'MANUAL' (PUT /api/v1/athlete/intensity-profile) or
-- 'GARMIN' (profile-sync merge). An observation row never retroactively certifies the origin of a
-- value that was applied before history existed: provenance (sourceTracked) is true only when the
-- LATEST applied=TRUE row matches the current profile exactly (see AthleteIntensityProfileService).
--
-- garmin_calendar_date_raw keeps Garmin's own measurement timestamp VERBATIM as text: the live
-- value ("2026-10-06T00:50:55.648") carries no UTC offset and Garmin does not document its zone,
-- so converting it to TIMESTAMPTZ would be a guess - same discipline as the 6D speed-unit rule.
-- garmin_fetched_at is RunningAI's own fetch time and is a real UTC instant.
--
-- No backfill: rows exist only for events after this migration. The pre-existing profile row keeps
-- its unknown origin by design (Phase 7B-4 requirement 4).
CREATE TABLE athlete_intensity_profile_history (
    id                                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id                             BIGINT                   NOT NULL,
    source                                 VARCHAR(16)              NOT NULL,
    applied                                BOOLEAN                  NOT NULL,
    lactate_threshold_heart_rate_bpm       INTEGER,
    lactate_threshold_pace_seconds_per_km  INTEGER,
    previous_heart_rate_bpm                INTEGER,
    previous_pace_seconds_per_km           INTEGER,
    garmin_calendar_date_raw               VARCHAR(40),
    garmin_fetched_at                      TIMESTAMP WITH TIME ZONE,
    recorded_at                            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_profile_history_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT ck_profile_history_source CHECK (source IN ('MANUAL', 'GARMIN'))
);

CREATE INDEX idx_profile_history_athlete_recorded
    ON athlete_intensity_profile_history (athlete_id, recorded_at DESC);
