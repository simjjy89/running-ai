-- Athlete-reported injury/pain status (Phase 7B-2). Append-only ledger: a new report is always
-- INSERTed, never UPDATEd, so the full history of what the athlete reported and when is preserved.
-- The "current" state for an athlete is simply its most recently recorded row (see
-- InjuryReportRepository.findFirstByAthleteIdOrderByRecordedAtDesc).
--
-- This records a self-reported symptom, never a medical diagnosis: there is no field for a cause,
-- a diagnosis or a treatment, only what the athlete observed and when.
CREATE TABLE injury_report (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id                  BIGINT                      NOT NULL,
    body_site                   VARCHAR(64),
    side                        VARCHAR(16),
    pain_present                BOOLEAN,
    pain_intensity              INTEGER,
    pain_on_walking             BOOLEAN,
    pain_on_stairs              BOOLEAN,
    swelling                    BOOLEAN,
    range_of_motion_limited     BOOLEAN,
    status                      VARCHAR(16)                 NOT NULL,
    notes                       VARCHAR(2000),
    reported_at                 TIMESTAMP WITH TIME ZONE    NOT NULL,
    recorded_at                 TIMESTAMP WITH TIME ZONE    NOT NULL,
    CONSTRAINT fk_injury_report_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT ck_injury_report_status CHECK (status IN ('ACTIVE', 'RESOLVED', 'UNKNOWN')),
    CONSTRAINT ck_injury_report_side CHECK (side IS NULL OR side IN ('LEFT', 'RIGHT', 'BOTH', 'UNSPECIFIED')),
    CONSTRAINT ck_injury_report_pain_intensity CHECK (pain_intensity IS NULL OR (pain_intensity BETWEEN 0 AND 10))
);

CREATE INDEX idx_injury_report_athlete_recorded ON injury_report (athlete_id, recorded_at DESC);
