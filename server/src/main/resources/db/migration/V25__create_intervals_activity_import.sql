-- Phase 7E-1 STEP 2: durable state of the Intervals.icu-only activity importer.
--
-- Why this table exists at all. Phase 7E-0 established that 27 of the athlete's past activities exist
-- ONLY in Intervals.icu (source OAUTH_CLIENT, 2026-08-02..09-13): Garmin Connect has no record before
-- 2026-09-18, so the Garmin-discovery-driven historical backfill (6H-6) can never reach them, however
-- wide its window (measured: a full 90-day re-run added 0 rows). They need their own import path, and
-- an import path that creates `activity` rows needs a durable record of what it decided per activity.
--
-- One row per (athlete, Intervals activity). That row is simultaneously:
--
--   * the IDEMPOTENCY key   - a second import of the same activity finds this row and skips, so a
--                             re-run adds no `activity` row and no sample row;
--   * the RESUME point      - each row is committed as its activity finishes, so re-invoking the
--                             endpoint after an interruption continues where it stopped instead of
--                             redoing finished work;
--   * the PROGRESS record   - outcome + reason_code say what happened to every candidate, including
--                             the ones deliberately NOT imported;
--   * the QUALITY record    - how many streams the source offered, how many were imported, which were
--                             missing, how many samples resulted, and what about the data could not be
--                             represented faithfully (quality_flags);
--   * the PROVENANCE record - the identifiers of the SAME workout in other systems, kept for the later
--                             Strava-archive recovery (Phase 7E-2) and for duplicate investigation.
--
-- What this table deliberately does NOT do: it never stores a Garmin activity id. The Intervals payload
-- of an OAUTH_CLIENT activity carries its own `external_id` (a client-generated UUID) and often a
-- `strava_id`; neither is a Garmin id, and no Garmin id is synthesised for an activity Garmin never saw.
--
-- outcome, as decided by IntervalsActivityImportService:
--   IMPORTED                  a new `activity` row was created from Intervals data
--   REFRESHED                 an already-imported Intervals activity was re-imported (source changed)
--   SKIPPED_ALREADY_IMPORTED  unchanged since the last import; nothing was written
--   LINKED_EXISTING           the same workout already exists from another source; the Intervals
--                             identity was attached to it instead of creating a second activity
--   SKIPPED_ALREADY_LINKED    that link already existed
--   SKIPPED_GARMIN_SOURCED    the payload says Garmin is its upstream; it belongs to the 6H-5
--                             enrichment path, never to this importer
--   SKIPPED_AMBIGUOUS         2+ existing activities could be the same workout - never merged
--                             automatically, a human decides
--   SKIPPED_UNSUPPORTED_TYPE  no ActivityType models this Intervals type (e.g. Ride, Workout)
--   SKIPPED_NO_SOURCE_DATA    the API itself returns no data for this activity (the STRAVA stubs)
--   FAILED                    attempted and failed; reason_code/last_error_code say why, attempt_count
--                             counts the tries. Re-invoking the endpoint retries exactly these.
CREATE TABLE intervals_activity_import (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id             BIGINT                   NOT NULL,
    intervals_activity_id  VARCHAR(100)             NOT NULL,
    activity_id            BIGINT,
    outcome                VARCHAR(32)              NOT NULL,
    reason_code            VARCHAR(64),

    -- provenance: who recorded it, and what the same workout is called elsewhere
    source_label           VARCHAR(32),
    source_external_id     VARCHAR(100),
    strava_activity_id     VARCHAR(100),
    device_name            VARCHAR(100),

    -- the source's own account of the session, kept so a later audit can re-check the normalisation
    -- without another API call
    activity_type_label    VARCHAR(32),
    started_at             TIMESTAMP WITH TIME ZONE,
    start_date_local       VARCHAR(32),
    elapsed_time_seconds   INTEGER,
    moving_time_seconds    INTEGER,
    distance_meters        DOUBLE PRECISION,
    source_lap_count       INTEGER,

    -- stream coverage and resulting fidelity
    stream_types_available INTEGER,
    stream_types_imported  INTEGER,
    missing_stream_types   VARCHAR(400),
    sample_count           INTEGER,
    sample_span_seconds    INTEGER,
    quality_flags          VARCHAR(400),

    -- change detection: the payload's own `analyzed` timestamp. A different value means Intervals
    -- recomputed the activity, which is the only reason to import an already-imported activity again.
    source_analyzed_at     TIMESTAMP WITH TIME ZONE,

    attempt_count          INTEGER                  NOT NULL,
    last_error_code        VARCHAR(64),
    imported_at            TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_intervals_activity_import_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT fk_intervals_activity_import_activity FOREIGN KEY (activity_id) REFERENCES activity (id),
    CONSTRAINT uk_intervals_activity_import UNIQUE (athlete_id, intervals_activity_id),
    CONSTRAINT ck_intervals_activity_import_attempts CHECK (attempt_count >= 0),
    CONSTRAINT ck_intervals_activity_import_outcome CHECK (outcome IN (
        'IMPORTED', 'REFRESHED', 'SKIPPED_ALREADY_IMPORTED', 'LINKED_EXISTING', 'SKIPPED_ALREADY_LINKED',
        'SKIPPED_GARMIN_SOURCED', 'SKIPPED_AMBIGUOUS', 'SKIPPED_UNSUPPORTED_TYPE', 'SKIPPED_NO_SOURCE_DATA',
        'FAILED'))
);

CREATE INDEX ix_intervals_activity_import_athlete_started
    ON intervals_activity_import (athlete_id, started_at);
