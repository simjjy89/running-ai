-- Phase 7E-2: durable state of the Strava archive (FIT) importer.
--
-- Why this path exists. Phase 7E-1 recovered the 27 activities that live only in Intervals.icu, but
-- Phase 7E-2 measured the athlete's full Strava export (94 activities, 2026-06-02..2026-10-11) and found
-- three things the Intervals path structurally cannot deliver:
--
--   1. 15 activities exist in NO other system (11 indoor rides, 4 treadmill runs, 2026-06-06..08-15).
--      Garmin has nothing before 2026-09-18 and Intervals returns a data-less stub for them.
--   2. Every one of the 25 Intervals-imported activities has ZERO laps stored, because Intervals reports
--      `icu_lap_count` = 0 for all of them - yet the Strava archive's FIT carries the athlete's real
--      manual lap presses, 5 of them with a genuine repetition structure.
--   3. Running power coverage in the FIT is markedly better than in the Intervals stream for ~10 of
--      those activities (measured: 2373 -> 6549 points on the 2026-08-18 long run).
--
-- The join is exact, never heuristic. Strava re-encodes each Apple Health workout into FIT and stamps
-- the developer field `apple_health_uuid` into the session message. That value is character-for-character
-- the `external_id` Intervals.icu stores for the same workout: measured 27/27, with 26 independently
-- corroborated by a matching Strava activity id and 0 contradictions. So an archive file is matched to a
-- stored activity by identifier alone - apple_health_uuid first, then the Strava activity id - and a
-- candidate that matches nothing is only then a new activity.
--
-- One row per (athlete, Strava activity). That row is simultaneously:
--
--   * the IDEMPOTENCY key - a second import finds this row, compares file_sha256, and does nothing;
--   * the RESUME point    - committed as each file finishes, so a re-invocation continues where it
--                           stopped; re-POSTing IS both the resume and the retry, as in 7E-1;
--   * the PROGRESS record - outcome + reason_code for every candidate, including those deliberately
--                           NOT imported (the 46 whose sport no ActivityType models);
--   * the QUALITY record  - what the FIT actually contained (record/lap counts, which sensor channels
--                           carried data) and what could not be represented faithfully (quality_flags);
--   * the PROVENANCE      - apple_health_uuid + the archive file name + its SHA-256, so any stored value
--                           can be traced back to the exact bytes it came from.
--
-- What it deliberately does NOT do: it never invents a Garmin id, never fabricates a lap intensity or
-- workout step index (the Strava re-encode carries neither, so interval GROUPS remain underivable for
-- those activities and that is recorded rather than guessed), and never overwrites a stored value that
-- is already present - enrichment only fills what is NULL.
--
-- outcome, as decided by StravaArchiveImportService:
--   IMPORTED                  a new `activity` row was created from the FIT
--   REFRESHED                 an already-imported archive activity was re-imported (file bytes changed)
--   SKIPPED_ALREADY_IMPORTED  unchanged since the last import; nothing was written
--   ENRICHED_EXISTING         the workout already exists from another source; laps and NULL-only sample
--                             metrics were added to it and no second activity was created
--   SKIPPED_ALREADY_ENRICHED  that enrichment was already applied from the same bytes
--   SKIPPED_AMBIGUOUS         2+ stored activities could be this workout - never merged automatically
--   SKIPPED_UNSUPPORTED_TYPE  no ActivityType models this FIT sport/sub_sport (strength, walk, stairs)
--   SKIPPED_NO_SENSOR_DATA    the FIT decoded but carries no usable record data
--   FAILED                    attempted and failed; reason_code/last_error_code say why
CREATE TABLE strava_activity_import (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_id             BIGINT                   NOT NULL,
    strava_activity_id     VARCHAR(100)             NOT NULL,
    activity_id            BIGINT,
    outcome                VARCHAR(32)              NOT NULL,
    reason_code            VARCHAR(64),

    -- provenance: the exact bytes this row was decided from, and the same workout's name elsewhere
    archive_filename       VARCHAR(200),
    file_sha256            VARCHAR(64),
    apple_health_uuid      VARCHAR(64),
    matched_by             VARCHAR(32),
    device_manufacturer    VARCHAR(64),

    -- the FIT's own account of the session, kept so a later audit needs no re-decode
    fit_sport              VARCHAR(40),
    fit_sub_sport          VARCHAR(40),
    activity_type          VARCHAR(32),
    started_at             TIMESTAMP WITH TIME ZONE,
    elapsed_time_seconds   INTEGER,
    timer_time_seconds     INTEGER,
    distance_meters        DOUBLE PRECISION,

    -- what the file actually contained, and what was done with it
    record_count           INTEGER,
    lap_count              INTEGER,
    sample_count           INTEGER,
    laps_written           INTEGER,
    samples_enriched       INTEGER,
    sensor_channels        VARCHAR(400),
    quality_flags          VARCHAR(400),

    attempt_count          INTEGER                  NOT NULL,
    last_error_code        VARCHAR(64),
    imported_at            TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_strava_activity_import_athlete FOREIGN KEY (athlete_id) REFERENCES athlete (id),
    CONSTRAINT fk_strava_activity_import_activity FOREIGN KEY (activity_id) REFERENCES activity (id),
    CONSTRAINT uk_strava_activity_import UNIQUE (athlete_id, strava_activity_id),
    CONSTRAINT ck_strava_activity_import_attempts CHECK (attempt_count >= 0),
    CONSTRAINT ck_strava_activity_import_outcome CHECK (outcome IN (
        'IMPORTED', 'REFRESHED', 'SKIPPED_ALREADY_IMPORTED', 'ENRICHED_EXISTING', 'SKIPPED_ALREADY_ENRICHED',
        'SKIPPED_AMBIGUOUS', 'SKIPPED_UNSUPPORTED_TYPE', 'SKIPPED_NO_SENSOR_DATA', 'FAILED'))
);

CREATE INDEX ix_strava_activity_import_athlete_started
    ON strava_activity_import (athlete_id, started_at);
